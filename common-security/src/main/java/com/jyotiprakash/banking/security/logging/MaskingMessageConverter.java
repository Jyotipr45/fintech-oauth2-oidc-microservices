package com.jyotiprakash.banking.security.logging;

import ch.qos.logback.classic.pattern.MessageConverter;
import ch.qos.logback.classic.spi.ILoggingEvent;

/**
 * Logback converter ({@code %maskedMsg}) that runs every formatted log message through
 * {@link SensitiveDataMasker}. Registered by {@code banking-logback-masking.xml}.
 *
 * @author Jyotiprakash Parida
 */
public class MaskingMessageConverter extends MessageConverter {

    @Override
    public String convert(ILoggingEvent event) {
        return SensitiveDataMasker.mask(super.convert(event));
    }
}
